export const translations: { en: LocaleDictionary<typeof english>; es: LocaleDictionary<typeof english> } = {
  en: english,
  es: spanish,
}

export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.en

export function translate<Section extends TranslationKey>(
  language: Language,
  section: Section,
  key: keyof (typeof translations.en)[Section] & string,
): string {
  return translations[language][section][key]
}
